import json

def get_all_keys(d, prefix=''):
    keys = {}
    for k, v in d.items():
        curr = f"{prefix}.{k}" if prefix else k
        if isinstance(v, dict):
            keys.update(get_all_keys(v, curr))
        else:
            keys[curr] = v
    return keys

