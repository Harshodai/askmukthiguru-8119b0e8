    def flatten(d, prefix=""):
        items = {}
        for k, v in d.items():
            curr = f"{prefix}.{k}" if prefix else k
            if isinstance(v, dict):
                items.update(flatten(v, curr))
            else:
                items[curr] = v
        return items

