def verify_and_save():
    with open("src/locales/en.json", "r", encoding="utf-8") as f:
        en = json.load(f)

    odia = build_odia_locale()

    def get_leaf_keys(d, prefix=""):
        res = {}
        for k, v in d.items():
            curr = f"{prefix}.{k}" if prefix else k
            if isinstance(v, dict):
                res.update(get_leaf_keys(v, curr))
            else:
                res[curr] = v
        return res

    en_leaves = get_leaf_keys(en)
    odia_leaves = get_leaf_keys(odia)

    missing_keys = set(en_leaves.keys()) - set(odia_leaves.keys())
    extra_keys = set(odia_leaves.keys()) - set(en_leaves.keys())

    print(f"EN leaf keys: {len(en_leaves)}")
    print(f"Odia leaf keys: {len(odia_leaves)}")
    print(f"Missing in Odia: {len(missing_keys)}")
    if missing_keys:
        print("MISSING KEYS:")
        for k in sorted(missing_keys):
            print(" -", k)
    print(f"Extra in Odia: {len(extra_keys)}")
    if extra_keys:
        print("EXTRA KEYS:")
        for k in sorted(extra_keys):
            print(" -", k)

    # Check placeholder preservation
    placeholder_mismatches = []
    for k in en_leaves:
        if k in odia_leaves:
            en_val = str(en_leaves[k])
            or_val = str(odia_leaves[k])
            en_ph = set(re.findall(r"\{\{[^}]+\}\}", en_val))
            or_ph = set(re.findall(r"\{\{[^}]+\}\}", or_val))
            if en_ph != or_ph:
                placeholder_mismatches.append((k, en_ph, or_ph, en_val, or_val))

    print(f"Placeholder mismatches: {len(placeholder_mismatches)}")
    for k, en_ph, or_ph, ev, ov in placeholder_mismatches:
        print(f"MISMATCH in {k}: EN {en_ph} vs OR {or_ph}")
        print(f"  EN: {ev}")
        print(f"  OR: {ov}")

    if not missing_keys and not extra_keys and not placeholder_mismatches:
        print("\nSUCCESS! Saving to src/locales/or.json...")
        with open("src/locales/or.json", "w", encoding="utf-8") as f:
            json.dump(odia, f, indent=2, ensure_ascii=False)
            f.write("\n")
        print("Saved successfully.")
        return True
    else:
        print("\nVerification FAILED. Not saving.")
        return False

if __name__ == "__main__":
    success = verify_and_save()
    sys.exit(0 if success else 1)
